/** "xem buổi học" for a known code; the raw code when unknown. */
export function permissionLabel(code: string): string {
  return (PERMISSION_LABELS as Record<string, string>)[code] ?? code;
}

/** Standard sentence for denied screens and actions. */
export function permissionDeniedDescription(code: string): string {
  return `Tài khoản hiện tại chưa được cấp quyền ${permissionLabel(code)}. Liên hệ quản trị viên nếu bạn cần quyền này.`;
}

/** Shorter sentence for inline action errors. */
export function permissionDeniedMessage(code: string): string {
  return `Tài khoản hiện tại không có quyền ${permissionLabel(code)}.`;
}
