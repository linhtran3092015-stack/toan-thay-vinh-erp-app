import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

const mocks = vi.hoisted(() => ({
  getDatabasePermissions: vi.fn(),
  revalidatePath: vi.fn(),
  rpc: vi.fn(),
  server: vi.fn(),
}));

vi.mock("@/lib/permissions/database-permissions", () => ({
  getCachedDatabasePermissions: mocks.getDatabasePermissions,
  getDatabasePermissions: mocks.getDatabasePermissions,
}));
vi.mock("@/lib/supabase/server", () => ({ createSupabaseServerClient: mocks.server }));
vi.mock("next/cache", () => ({ revalidatePath: mocks.revalidatePath }));

import {
  adminAdjustTimeEntryAction,
  adminDeleteTimeEntryAction,
} from "@/features/timekeeping/timekeeping-admin-actions";

const entryId = "c1111111-1111-4111-8111-111111111111";

beforeEach(() => {
  mocks.getDatabasePermissions.mockResolvedValue({ ok: true, permissions: ["timekeeping.approve_adjustment"] });
  mocks.server.mockResolvedValue({ rpc: mocks.rpc });
});

afterEach(() => {
  vi.clearAllMocks();
});

describe("adminDeleteTimeEntryAction", () => {
  // Generated by /ship test coverage audit (Claude Opus 5.5) — 2026-10-23
  // Value: protects=a delete without timekeeping.approve_adjustment (staff.manage alone is not enough, matching the RPC), a reason or a valid id never reaches the database; an allowed one sends the trimmed reason to
  // admin_delete_time_entry, shows each database refusal in Vietnamese, and only a returned row counts as success and revalidates /timekeeping;
  // fails_when=the permission check or schema parse is dropped or moved after the RPC, the RPC name/args drift, a refusal (payroll lock, open shift, no permission) shows the
  // generic error, an empty reply or a throw reports success, or the page is not revalidated;
  // why_new=no test covered timekeeping-admin-actions; the component test mocks this action; seam=none;
  // no_claim=does not prove the RPC's own checks or that it raises these codes (pgTAP covers them); permissions loader and Supabase client are mocked
  it("refuses unauthorised or invalid deletes before the database and maps admin_delete_time_entry outcomes", async () => {
    for (const permissions of [["timekeeping.view"], ["staff.manage"]]) {
      mocks.getDatabasePermissions.mockResolvedValueOnce({ ok: true, permissions });
      expect(await adminDeleteTimeEntryAction({ reason: "Chấm trùng ca", timeEntryId: entryId })).toEqual({
        fieldErrors: undefined,
        message: "Tài khoản hiện tại không có quyền xóa lượt chấm công.",
        status: "error",
      });
    }

    mocks.getDatabasePermissions.mockResolvedValueOnce({ ok: false });
    expect((await adminDeleteTimeEntryAction({ reason: "Chấm trùng ca", timeEntryId: entryId })).status).toBe("error");

    const blank = await adminDeleteTimeEntryAction({ reason: "   ", timeEntryId: entryId });
    expect(blank).toMatchObject({ message: "Dữ liệu xóa lượt chấm công chưa hợp lệ.", status: "error" });
    expect(blank.fieldErrors?.reason).toContain("Lý do xóa không được để trống.");

    const malformed = await adminDeleteTimeEntryAction({ reason: "Chấm trùng ca", timeEntryId: "entry-1" });
    expect(malformed.fieldErrors?.timeEntryId).toContain("ID lượt chấm công không hợp lệ.");

    expect(mocks.server).not.toHaveBeenCalled();
    expect(mocks.rpc).not.toHaveBeenCalled();
    expect(mocks.revalidatePath).not.toHaveBeenCalled();

    const refusals: Array<[string, string]> = [
      ["23514: TIME_ENTRY_LOCKED_BY_PAYROLL", "Lượt chấm công thuộc kỳ lương đã khoá (đang duyệt hoặc đã duyệt). Hãy mở lại kỳ lương về nháp trước khi thay đổi công; kỳ đã chi trả thì không mở lại được, hãy bù trừ ở kỳ sau."],
      ["23514: TIME_ENTRY_OPEN_CANNOT_BE_DELETED", "Ca đang diễn ra không thể xóa. Hãy sửa giờ ra hoặc chờ ca kết thúc."],
      ["23514: TIME_ENTRY_REFERENCED_BY_PAYROLL_HISTORY", "Lượt chấm công đã nằm trong bảng lương tính trước đây nên không thể xóa."],
      ["23514: TIME_ENTRY_DELETE_WOULD_RESTORE_IMPORTED_TIMEKEEPING", "Ngày này có công import từ Excel; xóa lượt chấm công cuối cùng sẽ làm bảng lương tính lại công import. Hãy sửa giờ thay vì xóa."],
      ["42501: TIMEKEEPING_APPROVE_ADJUSTMENT_PERMISSION_REQUIRED", "Tài khoản không có quyền điều chỉnh công của nhân sự."],
      ["P0002: TIME_ENTRY_NOT_FOUND", "Không tìm thấy lượt chấm công."],
      ["22023: TIME_ENTRY_DELETE_REASON_REQUIRED", "Vui lòng nhập lý do xóa lượt chấm công."],
      ["XX000: something unexpected", "Không thể hoàn tất thao tác. Dữ liệu chưa được cập nhật."],
    ];
    for (const [databaseMessage, shown] of refusals) {
      mocks.rpc.mockResolvedValueOnce({ data: null, error: { message: databaseMessage } });
      expect(await adminDeleteTimeEntryAction({ reason: "Chấm trùng ca", timeEntryId: entryId })).toMatchObject({
        message: shown,
        status: "error",
      });
    }

    mocks.rpc.mockResolvedValueOnce({ data: null, error: null });
    expect(await adminDeleteTimeEntryAction({ reason: "Chấm trùng ca", timeEntryId: entryId })).toMatchObject({
      message: "Database không trả về lượt chấm công vừa xóa.",
      status: "error",
    });

    mocks.rpc.mockRejectedValueOnce(new Error("fetch failed"));
    expect(await adminDeleteTimeEntryAction({ reason: "Chấm trùng ca", timeEntryId: entryId })).toMatchObject({
      message: "Không thể kết nối tới máy chủ để xóa lượt chấm công. Vui lòng thử lại.",
      status: "error",
    });
    expect(mocks.revalidatePath).not.toHaveBeenCalled();

    mocks.rpc.mockClear();
    mocks.rpc.mockResolvedValueOnce({ data: { id: entryId }, error: null });
    expect(await adminDeleteTimeEntryAction({ reason: "  Chấm trùng ca  ", timeEntryId: entryId })).toEqual({
      message: "Đã xóa lượt chấm công.",
      status: "success",
    });
    expect(mocks.rpc).toHaveBeenCalledExactlyOnceWith("admin_delete_time_entry", {
      p_reason: "Chấm trùng ca",
      p_time_entry_id: entryId,
    });
    expect(mocks.revalidatePath).toHaveBeenCalledWith("/timekeeping");
  });
});

describe("adminAdjustTimeEntryAction", () => {
  // Generated by /ship test coverage audit (Claude Opus 5.5) — 2026-10-23
  // Value: protects=a mode picked in the adjust dialog reaches admin_adjust_time_entry as p_mode, no mode is sent when none was picked, and the new no-change/bad-mode refusals read in Vietnamese;
  // fails_when=p_mode is dropped from the RPC args (optional in the generated types, so tsc stays green) and an online correction is saved as the old mode, or the new codes fall to the generic error;
  // why_new=the component test stops at the mocked action; pgTAP calls the RPC directly; seam=none;
  // no_claim=does not prove how the RPC applies the mode (pgTAP covers it); Supabase client is mocked
  it("forwards the chosen mode as p_mode and maps the re-adjust refusals", async () => {
    const input = {
      checkInAt: "2026-09-07T08:30:00+07:00",
      checkOutAt: "2026-09-07T12:30:00+07:00",
      reason: "Dạy trực tuyến",
      timeEntryId: entryId,
    };

    mocks.rpc.mockResolvedValueOnce({ data: { id: entryId }, error: null });
    expect((await adminAdjustTimeEntryAction({ ...input, mode: "online" })).status).toBe("success");
    expect(mocks.rpc).toHaveBeenLastCalledWith("admin_adjust_time_entry", {
      p_check_in_at: input.checkInAt,
      p_check_out_at: input.checkOutAt,
      p_mode: "online",
      p_reason: "Dạy trực tuyến",
      p_time_entry_id: entryId,
    });

    mocks.rpc.mockResolvedValueOnce({ data: { id: entryId }, error: null });
    await adminAdjustTimeEntryAction(input);
    expect(mocks.rpc.mock.lastCall?.[1]).toMatchObject({ p_mode: undefined });

    const refusals: Array<[string, string]> = [
      ["22023: TIME_ENTRY_ADJUSTMENT_NO_CHANGE", "Giờ và hình thức không thay đổi so với hiện tại."],
      ["22023: TIME_ENTRY_MODE_INVALID", "Hình thức chấm công không hợp lệ."],
      ["42501: TIMEKEEPING_MANAGE_PERMISSION_REQUIRED", "Tài khoản không có quyền điều chỉnh công của nhân sự."],
      ["23514: TIME_ENTRY_LOCKED_BY_PAYROLL", "Lượt chấm công thuộc kỳ lương đã khoá (đang duyệt hoặc đã duyệt). Hãy mở lại kỳ lương về nháp trước khi thay đổi công; kỳ đã chi trả thì không mở lại được, hãy bù trừ ở kỳ sau."],
      ["22023: TIME_ENTRY_ADJUSTMENT_CANNOT_USE_FUTURE_TIME", "Không thể điều chỉnh sang thời điểm trong tương lai."],
      ["22023: TIME_ENTRY_ADJUSTMENT_WORK_DATE_INVALID", "Giờ vào phải thuộc ngày làm việc của lượt chấm công và giờ ra không quá ngày hôm sau."],
    ];
    for (const [databaseMessage, shown] of refusals) {
      mocks.rpc.mockResolvedValueOnce({ data: null, error: { message: databaseMessage } });
      expect(await adminAdjustTimeEntryAction({ ...input, mode: "offline" })).toMatchObject({ message: shown, status: "error" });
    }

    expect((await adminAdjustTimeEntryAction({ ...input, mode: "hybrid" as "online" })).fieldErrors?.mode).toBeDefined();
    expect(mocks.rpc).toHaveBeenCalledTimes(8);
  });
});
