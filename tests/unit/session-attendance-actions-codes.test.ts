import { beforeEach, describe, expect, it, vi } from "vitest";

const rpcMock = vi.hoisted(() => vi.fn());
const permissionsMock = vi.hoisted(() => vi.fn());

vi.mock("@/lib/permissions/database-permissions", () => ({
  getDatabasePermissions: permissionsMock,
}));

vi.mock("@/lib/supabase/server", () => ({
  createSupabaseServerClient: vi.fn(async () => ({
    rpc: rpcMock,
  })),
}));

vi.mock("next/cache", () => ({
  revalidatePath: vi.fn(),
}));

import { revalidatePath } from "next/cache";

import { markSessionAttendanceAction, refreshSessionAttendanceAction, updateSessionAttendanceAction } from "@/features/sessions/actions/session-attendance-actions";
import {
  ATTENDANCE_CLIENT_ERROR_CODES,
  ATTENDANCE_RPC_ERROR_CODES,
  ATTENDANCE_SESSION_WIDE_ERROR_CODE_LIST,
  ATTENDANCE_SESSION_WIDE_ERROR_CODES,
} from "@/features/sessions/forms/attendance-action-types";

// Value: protects=the error codes the bulk "Có mặt cho tất cả" loop branches on (session-wide stop vs per-student failure);
// fails_when=the action drops `code` for a known RPC error or a missing attendance.mark, or invents one for an unknown error;
// seam=supabase client and permission lookup are mocked; no_claim=does not prove the database raises these messages
describe("markSessionAttendanceAction error codes", () => {
  const payload = {
    actualLearningMode: "offline" as const,
    attendanceStatus: "present" as const,
    classSessionId: "fa70d806-18e0-4b04-af6e-b045156a13fa",
    notes: null,
    studentId: "0b3c1a52-7d4e-4f1a-9a3b-2c5d6e7f8a90",
  };

  beforeEach(() => {
    rpcMock.mockReset();
    permissionsMock.mockReset();
    permissionsMock.mockResolvedValue({ ok: true, permissions: ["attendance.mark"] });
  });

  it("returns CLASS_SESSION_IS_LOCKED when the RPC error message contains it", async () => {
    rpcMock.mockResolvedValueOnce({
      data: null,
      error: { message: "P0001: CLASS_SESSION_IS_LOCKED" },
    });

    const result = await markSessionAttendanceAction(payload);

    expect(result.status).toBe("error");
    expect(result).toMatchObject({
      code: "CLASS_SESSION_IS_LOCKED",
      message: "Buổi học đã khóa nên không thể thay đổi điểm danh.",
    });
  });

  it("returns ATTENDANCE_MARK_PERMISSION_DENIED without calling the RPC when attendance.mark is missing", async () => {
    permissionsMock.mockResolvedValueOnce({ ok: true, permissions: ["sessions.view"] });

    const result = await markSessionAttendanceAction(payload);

    expect(result.status).toBe("error");
    expect(result).toMatchObject({ code: "ATTENDANCE_MARK_PERMISSION_DENIED" });
    expect(rpcMock).not.toHaveBeenCalled();
  });

  // Generated by /ship test audit pass 3 (Claude Opus 5.5) — 2026-10-13
  // Value: protects=a failed permission lookup returns the session-wide ATTENDANCE_PERMISSION_CHECK_FAILED code, so bulk marking stops;
  // fails_when=the lookup-failure branch drops its code, and mark-all retries every student with the same sign-in error;
  // why_new=only the denied-permission branch was covered; seam=none; no_claim=does not prove getDatabasePermissions fails this way (mocked)
  it("returns ATTENDANCE_PERMISSION_CHECK_FAILED without calling the RPC when the permission lookup fails", async () => {
    permissionsMock.mockResolvedValueOnce({ ok: false });

    const result = await markSessionAttendanceAction(payload);

    expect(result).toMatchObject({ code: "ATTENDANCE_PERMISSION_CHECK_FAILED", status: "error" });
    expect(ATTENDANCE_SESSION_WIDE_ERROR_CODES.has("ATTENDANCE_PERMISSION_CHECK_FAILED")).toBe(true);
    expect(rpcMock).not.toHaveBeenCalled();
  });

  // Generated by /ship review fixes (Claude) — 2026-10-13
  // Value: protects=every session-wide code the bulk loop stops on is one the action can actually return as `code` (from the RPC message or its own permission checks);
  // fails_when=a session-wide code is renamed or misspelled on one side, or knownMessages stops matching it, so mark-all keeps retrying every student after a session-wide failure;
  // why_new=only CLASS_SESSION_IS_LOCKED was round-tripped; the shared code list is new;
  // seam=supabase client and permission lookup are mocked; no_claim=does not prove the database raises these messages
  const rpcSessionWideCodes = ATTENDANCE_SESSION_WIDE_ERROR_CODE_LIST.filter((code) =>
    (ATTENDANCE_RPC_ERROR_CODES as readonly string[]).includes(code),
  );

  it.each(rpcSessionWideCodes)("round-trips the session-wide RPC code %s as `code`", async (code) => {
    rpcMock.mockResolvedValueOnce({ data: null, error: { message: `P0001: ${code}` } });

    const result = await markSessionAttendanceAction(payload);

    expect(result).toMatchObject({ code, status: "error" });
    expect(result.message).not.toBe("Không thể cập nhật điểm danh. Dữ liệu chưa được thay đổi.");
    expect(ATTENDANCE_SESSION_WIDE_ERROR_CODES.has(code)).toBe(true);
  });

  // Generated by /ship review fixes (Claude) — 2026-10-13
  // Value: protects=every database error code resolves to itself (substring matching in knownMessages order), not only the session-wide ones;
  // fails_when=a new code that contains another code shadows it and per-student failures come back with the wrong code/message;
  // why_new=the round trip above covers session-wide codes only; seam=supabase client mocked; no_claim=does not prove the database raises these messages
  it.each([...ATTENDANCE_RPC_ERROR_CODES])("maps the RPC message %s back to the same code", async (code) => {
    rpcMock.mockResolvedValueOnce({ data: null, error: { message: `P0001: ${code}` } });

    const result = await markSessionAttendanceAction(payload);

    expect(result).toMatchObject({ code, status: "error" });
  });

  it("covers every session-wide code by the RPC map or the action's own permission codes", () => {
    expect(rpcSessionWideCodes.length).toBeGreaterThan(0);
    for (const code of ATTENDANCE_SESSION_WIDE_ERROR_CODES) {
      expect([...ATTENDANCE_RPC_ERROR_CODES, ...ATTENDANCE_CLIENT_ERROR_CODES]).toContain(code);
    }
  });

  it("returns no code for an unknown RPC error", async () => {
    rpcMock.mockResolvedValueOnce({
      data: null,
      error: { message: "XX000: SOMETHING_UNEXPECTED" },
    });

    const result = await markSessionAttendanceAction(payload);

    expect(result.status).toBe("error");
    expect(result).not.toHaveProperty("code");
    expect(result.message).toBe("Không thể cập nhật điểm danh. Dữ liệu chưa được thay đổi.");
  });
});

// Value: protects=a bulk save skips the per-student page re-render while a single save still refreshes the page;
// fails_when=deferRefresh is ignored (bulk marking re-renders the whole session page once per student) or leaks into the RPC,
// or a plain save stops revalidating (the row would stay unmarked until a manual reload);
// why_new=deferRefresh is new with the attendance speed-up; seam=supabase client and next/cache mocked; no_claim=does not time a real render
describe("markSessionAttendanceAction page refresh", () => {
  const payload = {
    actualLearningMode: "offline" as const,
    attendanceStatus: "present" as const,
    classSessionId: "fa70d806-18e0-4b04-af6e-b045156a13fa",
    notes: null,
    studentId: "0b3c1a52-7d4e-4f1a-9a3b-2c5d6e7f8a90",
  };
  const saved = { data: { class_session_id: payload.classSessionId, id: "5d1f0a8e-2b7c-4c3d-9e8f-1a2b3c4d5e6f" }, error: null };

  beforeEach(() => {
    rpcMock.mockReset();
    vi.mocked(revalidatePath).mockClear();
    permissionsMock.mockResolvedValue({ ok: true, permissions: ["attendance.mark"] });
  });

  it("revalidates the session page after a single save", async () => {
    rpcMock.mockResolvedValueOnce(saved);

    await expect(markSessionAttendanceAction(payload)).resolves.toMatchObject({ status: "success" });

    expect(revalidatePath).toHaveBeenCalledWith(`/sessions/${payload.classSessionId}`);
  });

  it("skips revalidation when the caller defers the refresh, and keeps the flag out of the RPC", async () => {
    rpcMock.mockResolvedValueOnce(saved);

    await expect(markSessionAttendanceAction({ ...payload, deferRefresh: true })).resolves.toMatchObject({ status: "success" });

    expect(revalidatePath).not.toHaveBeenCalled();
    expect(rpcMock.mock.calls[0][1]).not.toHaveProperty("p_defer_refresh");
    expect(Object.keys(rpcMock.mock.calls[0][1]).sort()).toEqual([
      "p_actual_learning_mode",
      "p_attendance_status",
      "p_class_session_id",
      "p_notes",
      "p_student_id",
    ]);
  });
});

// Generated by /ship test audit (Claude) — 2026-10-24
// Value: protects=an attendance edit revalidates /sessions/{id} of the session the RPC returns, and a refused edit does not;
// fails_when=the update action stops revalidating (the edited row keeps its old status, the client no longer refreshes) or uses the wrong id;
// why_new=only markSessionAttendanceAction's revalidation was covered; the editor's router.refresh() was removed; seam=none;
// no_claim=supabase, permissions and next/cache are mocked; does not prove Next re-renders the page
describe("updateSessionAttendanceAction page refresh", () => {
  const classSessionId = "3c9e4b2a-6d1f-4e8a-b7c5-0f2e1d3a4b5c";
  const payload = {
    actualLearningMode: "offline" as const,
    attendanceId: "5d1f0a8e-2b7c-4c3d-9e8f-1a2b3c4d5e6f",
    attendanceStatus: "excused_absence" as const,
    notes: null,
    reason: "Phụ huynh báo nghỉ",
  };

  beforeEach(() => {
    rpcMock.mockReset();
    vi.mocked(revalidatePath).mockClear();
    permissionsMock.mockResolvedValue({ ok: true, permissions: ["attendance.mark"] });
  });

  it("revalidates the session page returned by the RPC after an edit", async () => {
    rpcMock.mockResolvedValueOnce({ data: { class_session_id: classSessionId, id: payload.attendanceId }, error: null });

    await expect(updateSessionAttendanceAction(payload)).resolves.toMatchObject({ classSessionId, status: "success" });

    expect(rpcMock).toHaveBeenCalledWith("update_session_attendance", expect.objectContaining({ p_session_attendance_id: payload.attendanceId }));
    expect(revalidatePath).toHaveBeenCalledWith(`/sessions/${classSessionId}`);
  });

  it("does not revalidate when the RPC refuses the edit", async () => {
    rpcMock.mockResolvedValueOnce({ data: null, error: { message: "P0001: CLASS_SESSION_IS_LOCKED" } });

    await expect(updateSessionAttendanceAction(payload)).resolves.toMatchObject({ code: "CLASS_SESSION_IS_LOCKED", status: "error" });

    expect(revalidatePath).not.toHaveBeenCalled();
  });
});

// Generated by /ship review fixes (Claude) — 2026-10-24
// Value: protects=the one refresh after deferred saves revalidates both the session page and the sessions list, only for a valid
// session id and a user who may still mark attendance; fails_when=the list is not revalidated (Back shows stale tallies), an invalid id
// or a signed-out/denied user can trigger revalidation, or a refusal is reported as ok; why_new=refreshSessionAttendanceAction is new;
// seam=none; no_claim=permissions and next/cache are mocked; does not prove Next re-renders either page
describe("refreshSessionAttendanceAction", () => {
  const classSessionId = "3c9e4b2a-6d1f-4e8a-b7c5-0f2e1d3a4b5c";

  beforeEach(() => {
    vi.mocked(revalidatePath).mockClear();
    permissionsMock.mockReset();
  });

  it("revalidates the session page and the sessions list once", async () => {
    permissionsMock.mockResolvedValue({ ok: true, permissions: ["attendance.mark"] });

    await expect(refreshSessionAttendanceAction(classSessionId)).resolves.toEqual({ ok: true });

    expect(revalidatePath).toHaveBeenCalledWith("/sessions");
    expect(revalidatePath).toHaveBeenCalledWith(`/sessions/${classSessionId}`);
    expect(revalidatePath).toHaveBeenCalledTimes(2);
  });

  it.each([
    { name: "an invalid session id", permissions: { ok: true, permissions: ["attendance.mark"] }, sessionId: "not-a-uuid" },
    { name: "a user without attendance.mark", permissions: { ok: true, permissions: ["attendance.view"] }, sessionId: classSessionId },
    { name: "a signed-out user", permissions: { error: { code: "not_authenticated", message: "x" }, ok: false }, sessionId: classSessionId },
  ])("refuses $name without revalidating", async ({ permissions, sessionId }) => {
    permissionsMock.mockResolvedValue(permissions);

    await expect(refreshSessionAttendanceAction(sessionId)).resolves.toEqual({ ok: false });

    expect(revalidatePath).not.toHaveBeenCalled();
  });
});
