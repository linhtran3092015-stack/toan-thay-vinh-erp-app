// Value: protects=the /dev/ preview bypass in proxy.ts opens only outside production and never widens to sibling paths;
// fails_when=/dev/ui redirects to /login under NODE_ENV=test, /dev/ui is served unauthenticated in production, or a /dev-prefixed route like /devices becomes public;
// why_new=the bypass landed in redesign step 1 untested, and the Coaching cases above only assert the token-route branch;
// seam=none; no_claim=does not prove Next strips /dev routes from the production build (route-level concern, outside the proxy)
describe("component preview route access (/dev/)", () => {
  afterEach(() => {
    vi.unstubAllEnvs();
  });

  it("serves /dev/ previews without authentication outside production", async () => {
    const response = await proxy(new NextRequest("http://localhost:3001/dev/ui"));

    expect(process.env.NODE_ENV).not.toBe("production");
    expect(response.status).toBe(200);
    expect(response.headers.get("location")).toBeNull();
  });

  it("keeps /dev/ previews behind the login gate in production", async () => {
    vi.stubEnv("NODE_ENV", "production");

    const response = await proxy(new NextRequest("http://localhost:3001/dev/ui"));

    expect(response.status).toBe(307);
    expect(response.headers.get("location")).toContain("/login");
  });

  it("does not widen the bypass to routes that merely start with /dev", async () => {
    const response = await proxy(new NextRequest("http://localhost:3001/devices"));

    expect(response.status).toBe(307);
    expect(response.headers.get("location")).toContain("/login");
  });

  // Value: protects=src/app/dev/layout.tsx 404s every /dev/* preview in production, so a signed-in staff member never reaches fixture pages; fails_when=the NODE_ENV check is dropped/inverted or the layout stops calling notFound(); why_new=the proxy cases only cover signed-out requests, nothing exercised the layout gate; seam=none; no_claim=does not prove next build omits the routes or that each preview page has its own check
  it("404s every /dev/ preview through the layout in production, signed in or not", async () => {
    const { default: DevLayout } = await import("@/app/dev/layout");

    expect(DevLayout({ children: "preview" })).toBe("preview");

    vi.stubEnv("NODE_ENV", "production");
    let thrown: unknown;
    try {
      DevLayout({ children: "preview" });
    } catch (error) {
      thrown = error;
    }

    expect((thrown as { digest?: string } | undefined)?.digest).toMatch(/404/);
  });
});
