import { beforeEach, describe, expect, it, vi } from "vitest";

const supabase = vi.hoisted(() => ({
  auth: { getUser: vi.fn() },
  rpc: vi.fn(),
}));

vi.mock("@/lib/env", () => ({ isSupabaseConfigured: () => true }));
vi.mock("@/lib/supabase/server", () => ({ createSupabaseServerClient: vi.fn(async () => supabase) }));

import { getDatabasePermissions } from "@/lib/permissions/database-permissions";

// Value: protects=the permission rows are only trusted after getUser() verified the session, now that both calls go out together;
// fails_when=the parallel load returns the RPC's rows while getUser() failed or found no user, or reports a failed RPC as success;
// why_new=getUser and get_my_permissions were sequential before the attendance speed-up and no test covered the real loader;
// seam=supabase client mocked; no_claim=does not prove get_my_permissions scopes rows to auth.uid() (RLS/RPC body)
describe("getDatabasePermissions", () => {
  beforeEach(() => {
    supabase.auth.getUser.mockReset();
    supabase.rpc.mockReset();
    vi.spyOn(console, "error").mockImplementation(() => {});
  });

  it("starts both reads before either answers and returns the verified user's permissions", async () => {
    let answerUser: (value: unknown) => void = () => {};
    supabase.auth.getUser.mockImplementation(() => new Promise((resolve) => { answerUser = resolve; }));
    supabase.rpc.mockResolvedValue({ data: [{ permission_code: "app.access" }, { permission_code: "attendance.mark" }, { permission_code: "app.access" }], error: null });

    const pending = getDatabasePermissions();
    await vi.waitFor(() => expect(supabase.rpc).toHaveBeenCalledWith("get_my_permissions"));
    answerUser({ data: { user: { id: "user-1" } }, error: null });

    await expect(pending).resolves.toEqual({ ok: true, permissions: ["app.access", "attendance.mark"] });
  });

  it("ignores the permission rows when getUser() fails", async () => {
    supabase.auth.getUser.mockResolvedValue({ data: { user: null }, error: { message: "JWT expired", status: 401 } });
    supabase.rpc.mockResolvedValue({ data: [{ permission_code: "app.access" }], error: null });

    await expect(getDatabasePermissions()).resolves.toEqual({
      error: { code: "not_authenticated", message: "An authenticated user is required." },
      ok: false,
    });
  });

  it("ignores the permission rows when there is no signed-in user", async () => {
    supabase.auth.getUser.mockResolvedValue({ data: { user: null }, error: null });
    supabase.rpc.mockResolvedValue({ data: [{ permission_code: "app.access" }], error: null });

    await expect(getDatabasePermissions()).resolves.toMatchObject({ error: { code: "not_authenticated" }, ok: false });
  });

  it("reports a failed permission query for a verified user", async () => {
    supabase.auth.getUser.mockResolvedValue({ data: { user: { id: "user-1" } }, error: null });
    supabase.rpc.mockResolvedValue({ data: null, error: { code: "42501", details: null, message: "permission denied" } });

    await expect(getDatabasePermissions()).resolves.toMatchObject({ error: { code: "query_failed" }, ok: false });
  });

  // Generated by /ship test audit (Claude Opus 5.5) — 2026-10-24
  // Value: protects=a signed-out or expired session stays not_authenticated (app shell redirects to login, export answers 401) although the RPC sent alongside getUser() fails too;
  // fails_when=the RPC error check moves ahead of the user check, so anon or expired visitors get query_failed (permission error page, export 503) and a query_failed log;
  // why_new=the cases above pair a getUser() failure with a successful RPC, but get_my_permissions is revoked from anon, so both fail together in production; seam=none;
  // no_claim=supabase client mocked; does not prove the exact error PostgREST returns for anon or an expired JWT
  it.each([
    {
      name: "an anonymous visitor",
      rpc: { data: null, error: { code: "42501", details: null, message: "permission denied for function get_my_permissions" } },
      user: { data: { user: null }, error: null },
    },
    {
      name: "an expired session",
      rpc: { data: null, error: { code: "PGRST301", details: null, message: "JWT expired" } },
      user: { data: { user: null }, error: { message: "JWT expired", status: 401 } },
    },
  ])("treats $name as signed out even though the permission RPC fails with it", async ({ rpc, user }) => {
    const errorLog = vi.spyOn(console, "error").mockImplementation(() => {});
    errorLog.mockClear();
    supabase.auth.getUser.mockResolvedValue(user);
    supabase.rpc.mockResolvedValue(rpc);

    await expect(getDatabasePermissions()).resolves.toEqual({
      error: { code: "not_authenticated", message: "An authenticated user is required." },
      ok: false,
    });
    expect(errorLog.mock.calls.flat().join(" ")).not.toContain("query_failed");
  });
});
