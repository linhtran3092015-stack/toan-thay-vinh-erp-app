import { describe, expect, it } from "vitest";

import {
  getStudentDirectoryMetricCell,
  summarizeDirectoryAttendance,
  summarizeDirectoryDebt,
  type StudentDirectoryMetrics,
} from "@/features/students/student-directory-metrics";

describe("summarizeDirectoryAttendance", () => {
  it("rates present over main sessions and leaves additional study out", () => {
    const rates = summarizeDirectoryAttendance([
      { attendance_status: "present", student_id: "a" },
      { attendance_status: "present", student_id: "a" },
      { attendance_status: "present", student_id: "a" },
      { attendance_status: "excused_absence", student_id: "a" },
      { attendance_status: "additional_study", student_id: "a" },
      { attendance_status: "unexcused_absence", student_id: "b" },
      { attendance_status: "additional_study", student_id: "c" },
      { attendance_status: "something_new", student_id: "c" },
    ]);

    expect(rates).toEqual({ a: 75, b: 0 });
  });
});

describe("summarizeDirectoryDebt", () => {
  const now = new Date("2026-10-13T00:00:00.000Z");
  const recent = "2026-10-10T08:00:00.000+00:00";
  const old = "2026-09-20T08:00:00.000+00:00";

  it("sums what is still owed on open requests only", () => {
    const debt = summarizeDirectoryDebt(
      [
        { created_at: recent, expected_amount_vnd: "2400000", paid_amount_vnd: "0", status: "pending", student_id: "a" },
        { created_at: recent, expected_amount_vnd: 1_200_000, paid_amount_vnd: 200_000, status: "partially_paid", student_id: "a" },
        { created_at: recent, expected_amount_vnd: 900_000, paid_amount_vnd: 900_000, status: "partially_paid", student_id: "b" },
        { created_at: old, expected_amount_vnd: 500_000, paid_amount_vnd: 0, status: "cancelled", student_id: "b" },
        { created_at: recent, expected_amount_vnd: 100_000, paid_amount_vnd: 300_000, status: "pending", student_id: "c" },
      ],
      now,
    );

    expect(debt).toEqual({ a: { amountVnd: 3_400_000, overdue: false } });
  });

  // Generated by /ship review fixes (Claude) — 2026-10-13
  // Value: protects=debt is overdue only for a pending request created over 14 days ago, matching the dashboard's payments_overdue;
  // fails_when=the cutoff drifts from 14 days, a partially paid or recent request marks a student overdue, or one overdue request is lost when summed;
  // why_new=the overdue rule is new with the two-level debt colours; seam=none; no_claim=does not prove the dashboard RPC still uses 14 days
  it("flags overdue debt like the dashboard: a pending request older than 14 days", () => {
    const debt = summarizeDirectoryDebt(
      [
        { created_at: old, expected_amount_vnd: 600_000, paid_amount_vnd: 0, status: "pending", student_id: "late" },
        { created_at: recent, expected_amount_vnd: 300_000, paid_amount_vnd: 0, status: "pending", student_id: "late" },
        { created_at: old, expected_amount_vnd: 600_000, paid_amount_vnd: 100_000, status: "partially_paid", student_id: "paying" },
        { created_at: "2026-09-29T00:00:00.000Z", expected_amount_vnd: 200_000, paid_amount_vnd: 0, status: "pending", student_id: "edge" },
        { created_at: "2026-09-28T23:59:59.000Z", expected_amount_vnd: 200_000, paid_amount_vnd: 0, status: "pending", student_id: "past" },
      ],
      now,
    );

    expect(debt).toEqual({
      edge: { amountVnd: 200_000, overdue: false },
      late: { amountVnd: 900_000, overdue: true },
      past: { amountVnd: 200_000, overdue: true },
      paying: { amountVnd: 500_000, overdue: false },
    });
  });
});

describe("getStudentDirectoryMetricCell", () => {
  const metrics: StudentDirectoryMetrics = {
    attendanceRate: { byStudentId: { a: 90 }, status: "ready" },
    balanceSessions: { byStudentId: { a: -2 }, status: "ready" },
    outstandingVnd: { reason: "failed", status: "unavailable" },
  };

  it("reads values and treats a missing balance as zero", () => {
    expect(getStudentDirectoryMetricCell(metrics, "attendanceRate", "a")).toEqual({ kind: "value", value: 90 });
    expect(getStudentDirectoryMetricCell(metrics, "balanceSessions", "a")).toEqual({ kind: "value", value: -2 });
    expect(getStudentDirectoryMetricCell(metrics, "balanceSessions", "z")).toEqual({ kind: "value", value: 0 });
  });

  it("carries the overdue flag of a debt cell", () => {
    const withDebt: StudentDirectoryMetrics = {
      ...metrics,
      outstandingVnd: { byStudentId: { a: { amountVnd: 600_000, overdue: true } }, status: "ready" },
    };

    expect(getStudentDirectoryMetricCell(withDebt, "outstandingVnd", "a")).toEqual({ kind: "value", overdue: true, value: 600_000 });
    expect(getStudentDirectoryMetricCell(withDebt, "outstandingVnd", "z")).toEqual({ kind: "value", value: 0 });
  });

  it("never turns a missing attendance rate or an unavailable column into zero", () => {
    expect(getStudentDirectoryMetricCell(metrics, "attendanceRate", "z")).toMatchObject({ kind: "empty" });
    expect(getStudentDirectoryMetricCell(metrics, "outstandingVnd", "a")).toEqual({
      kind: "unavailable",
      reason: "Không tải được công nợ",
    });
  });
});
