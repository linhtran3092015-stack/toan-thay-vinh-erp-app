import { cleanup, fireEvent, render, screen, within } from "@testing-library/react";
import { afterEach, describe, expect, it } from "vitest";

import { TopbarTimekeepingButton } from "@/components/layout/topbar-timekeeping-button";
import { Topbar } from "@/components/layout/topbar";
import { getNavigationBreadcrumb, getVisibleNavigationDomains } from "@/config/navigation";

afterEach(() => {
  cleanup();
});

describe("TopbarTimekeepingButton", () => {
  it("renders default attendance button with explicit white text styling when no open entry exists", () => {
    render(<TopbarTimekeepingButton hasOpenEntry={false} />);

    const link = screen.getByRole("link", { name: "Chấm công ngay" });
    expect(link).toHaveAttribute("href", "/timekeeping");
    expect(link).toHaveTextContent("Chấm công");
    expect(link.className).toContain("text-white");
  });

  it("renders active attendance status button with explicit white text styling when an open entry exists", () => {
    render(<TopbarTimekeepingButton hasOpenEntry />);

    const link = screen.getByRole("link", { name: "Đang trong ca chấm công - Ra ca" });
    expect(link).toHaveAttribute("href", "/timekeeping");
    expect(link).toHaveTextContent("Đang chấm công");
    expect(link.className).toContain("text-white");
  });

  it("renders Topbar with the attendance button next to the bell and user menu when user has timekeeping permission", () => {
    render(
      <Topbar
        canCheckTimekeeping
        hasOpenTimekeepingEntry={false}
        mobileMenuTriggerRef={{ current: null }}
        onMenuClick={() => {}}
        unreadNotificationCount={0}
        user={{ displayName: "Test Assistant", email: "ta@example.com", id: "user-1", initials: "TA" }}
      />,
    );

    expect(screen.getByRole("link", { name: "Chấm công ngay" })).toBeInTheDocument();
    expect(screen.getByRole("link", { name: "Thông báo" })).toHaveAttribute("href", "/notifications");
    fireEvent.click(screen.getByRole("button", { name: "Tài khoản: Test Assistant" }));
    expect(screen.getByRole("menuitem", { name: /Giao diện/i })).toBeInTheDocument();
    expect(screen.getByRole("menuitem", { name: "Đăng xuất" })).toBeInTheDocument();
  });

  it("hides attendance button when user lacks timekeeping permission", () => {
    render(
      <Topbar
        canCheckTimekeeping={false}
        mobileMenuTriggerRef={{ current: null }}
        onMenuClick={() => {}}
        unreadNotificationCount={0}
        user={{ displayName: "Unauthorized Staff", email: "unauth@example.com", id: "user-2", initials: "US" }}
      />,
    );

    expect(screen.queryByRole("link", { name: /Chấm công/i })).not.toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Tài khoản: Unauthorized Staff" })).toBeInTheDocument();
  });
});

// Generated by /ship test audit (Claude Fable 5.1) — 2026-10-12
// Value: protects=Topbar paints the real-route breadcrumb (domain link + aria-current module) and the bell's unread count with the 99+ cap;
// fails_when=/students/<id> loses its "Học sinh" crumb, a finance route drops the "Tài chính" link, the bell label omits the count, or 120 unread paints 120;
// why_new=getNavigationBreadcrumb is unit-tested but nothing renders the crumb through Topbar, and the bell was only asserted at zero unread;
// seam=none; no_claim=does not prove the app shell computes the breadcrumb from the live pathname (shell wiring is untested here)
describe("Topbar breadcrumb and notifications (design 01)", () => {
  const user = { displayName: "Owner", email: "owner@example.com", id: "user-3", initials: "OW" };
  const domains = getVisibleNavigationDomains(["students.view", "finance.view", "tuition_periods.view"]);

  it("renders the current module as the page crumb for a nested student route", () => {
    render(
      <Topbar
        breadcrumb={getNavigationBreadcrumb("/students/abc", domains)}
        mobileMenuTriggerRef={{ current: null }}
        onMenuClick={() => {}}
        unreadNotificationCount={5}
        user={user}
      />,
    );

    const nav = screen.getByRole("navigation", { name: "Vị trí hiện tại" });
    expect(within(nav).getByText("Học sinh")).toHaveAttribute("aria-current", "page");
    expect(within(nav).queryByRole("link")).not.toBeInTheDocument();

    const bell = screen.getByRole("link", { name: "Thông báo, 5 chưa đọc" });
    expect(bell).toHaveAttribute("href", "/notifications");
    expect(bell).toHaveTextContent("5");
  });

  it("links the domain before the module crumb and caps the unread badge at 99+", () => {
    render(
      <Topbar
        breadcrumb={getNavigationBreadcrumb("/finance/tuition-periods/abc", domains)}
        mobileMenuTriggerRef={{ current: null }}
        onMenuClick={() => {}}
        unreadNotificationCount={120}
        user={user}
      />,
    );

    const nav = screen.getByRole("navigation", { name: "Vị trí hiện tại" });
    expect(within(nav).getByRole("link", { name: "Tài chính" })).toHaveAttribute("href", "/finance");
    expect(within(nav).getByText("Kỳ thu học phí")).toHaveAttribute("aria-current", "page");

    const bell = screen.getByRole("link", { name: "Thông báo, 120 chưa đọc" });
    expect(bell).toHaveTextContent("99+");
    expect(bell).not.toHaveTextContent("120");
  });

  it("omits the breadcrumb landmark for a route outside the navigation", () => {
    render(
      <Topbar
        breadcrumb={getNavigationBreadcrumb("/unknown", domains)}
        mobileMenuTriggerRef={{ current: null }}
        onMenuClick={() => {}}
        unreadNotificationCount={0}
        user={user}
      />,
    );

    expect(screen.queryByRole("navigation", { name: "Vị trí hiện tại" })).not.toBeInTheDocument();
    expect(screen.getByRole("link", { name: "Thông báo" })).not.toHaveTextContent(/\d/);
  });
});
