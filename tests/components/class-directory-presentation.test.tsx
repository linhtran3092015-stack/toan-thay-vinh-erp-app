import { createRef, useRef, useState } from "react";
import { cleanup, fireEvent, render, screen, within } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";

import {
  ClassFilters,
  ClassListPage,
} from "@/features/classes/class-list-page";
import { countActiveClassFilters, defaultClassFilters } from "@/features/classes/class-filters";
import type { ClassDirectoryItem } from "@/features/classes/read-models";

/**
 * URL state lives in the query string. The page writes it through the History API
 * (Next syncs that with useSearchParams); the spies feed the next render's params like Next would.
 */
const navigation = vi.hoisted(() => {
  const state = { params: new URLSearchParams() };
  const apply = (_state: unknown, _unused: string, href?: string | URL | null) => {
    state.params = new URLSearchParams(String(href ?? "").split("?")[1] ?? "");
  };
  return { apply, state };
});
vi.mock("next/navigation", () => ({
  useSearchParams: () => navigation.state.params,
}));
const historySpies = {
  push: vi.spyOn(window.history, "pushState").mockImplementation(navigation.apply),
  replace: vi.spyOn(window.history, "replaceState").mockImplementation(navigation.apply),
};

afterEach(() => {
  cleanup();
  navigation.state.params = new URLSearchParams();
  historySpies.push.mockClear();
  historySpies.replace.mockClear();
});

const classWithoutStudentCount: ClassDirectoryItem = {
  academicYear: { code: "2025-2026", endsOn: "2026-05-31", id: "year-1", isCurrent: true, name: "Năm học 2025-2026", startsOn: "2025-08-01", status: "active" },
  activeScheduleCount: 2,
  activeStudentCount: null,
  code: "7A",
  defaultLearningMode: "offline",
  grade: 7,
  id: "class-1",
  level: "A",
  name: "Toán 7A",
  notes: null,
  status: "active",
  weeklySessionCount: 2,
};

describe("Classes directory presentation", () => {
  it("announces active filters in the narrow drawer and clears them on reset", () => {
    function Harness() {
      const [filters, setFilters] = useState(defaultClassFilters);
      return <ClassFilters activeFilterCount={countActiveClassFilters(filters)} filters={filters} isOpen onClose={vi.fn()} onFilterChange={(key, value) => setFilters((current) => ({ ...current, [key]: value }))} onReset={() => setFilters(defaultClassFilters)} returnFocusRef={createRef()} years={[]} />;
    }
    const view = render(<Harness />);
    expect(screen.getByText("Lọc danh sách lớp học hiện có")).toBeInTheDocument();
    fireEvent.change(screen.getByTestId("mobile-class-status"), { target: { value: "active" } });
    fireEvent.change(screen.getByTestId("mobile-class-grade"), { target: { value: "7" } });
    expect(screen.getByText("2 bộ lọc đang áp dụng")).toBeInTheDocument();
    fireEvent.click(screen.getByTestId("mobile-class-reset-filters"));
    expect(screen.getByText("Lọc danh sách lớp học hiện có")).toBeInTheDocument();
    view.unmount();
  });

  it("labels, dismisses, and restores focus from the filter drawer", () => {
    function Harness() {
      const [isOpen, setIsOpen] = useState(false);
      const trigger = useRef<HTMLButtonElement>(null);
      return <><button onClick={() => setIsOpen(true)} ref={trigger} type="button">Mở bộ lọc</button><ClassFilters activeFilterCount={0} filters={defaultClassFilters} isOpen={isOpen} onClose={() => setIsOpen(false)} onFilterChange={vi.fn()} onReset={vi.fn()} returnFocusRef={trigger} years={[]} /></>;
    }
    render(<Harness />);
    const trigger = screen.getByRole("button", { name: "Mở bộ lọc" });
    fireEvent.click(trigger);
    fireEvent.keyDown(screen.getByRole("dialog", { name: "Bộ lọc" }), { key: "Escape" });
    expect(trigger).toHaveFocus();
  });

  it("presents a withheld student count as permission state, never zero", () => {
    render(<ClassListPage canCreateClass={false} classes={[classWithoutStudentCount]} />);

    const record = screen.getByRole("listitem");
    expect(record).toHaveTextContent("Học viên: Không có quyền");
    expect(record).not.toHaveTextContent("Học viên: 0");
  });
});

// Generated by /ship test audit (Claude Fable 5.1) — 2026-10-12
// Value: protects=/classes status chips carry live counts and narrow the table via the URL, and a no-match filter shows the in-frame empty state whose Xóa lọc restores rows;
// fails_when=chip counts drift, a zero chip is clickable, pressing Nháp keeps active rows, a no-match search still paints rows, or Xóa lọc restores nothing;
// why_new=the cases above cover the drawer and the withheld count, none drive the chips or the empty-by-filter path of ClassListPage (flow F7);
// seam=none; no_claim=does not prove Next re-renders on history.replaceState (the harness applies the href to the search params itself)
describe("Classes directory quick chips and empty-by-filter (design 06b)", () => {
  const classes: ClassDirectoryItem[] = [
    { ...classWithoutStudentCount, activeStudentCount: 18 },
    { ...classWithoutStudentCount, activeStudentCount: 12, code: "8B", grade: 8, id: "class-2", level: "B", name: "Toán 8B" },
    { ...classWithoutStudentCount, activeStudentCount: 0, code: "9C", grade: 9, id: "class-3", name: "Toán 9C", status: "draft" },
  ];
  const chip = (label: string, count: number) => new RegExp(`^${label}\\s?${count}$`);
  const dataRows = () => within(screen.getByRole("table", { name: "Danh sách lớp học" })).queryAllByRole("row").slice(1);

  it("counts each status and narrows the table when a chip is pressed", () => {
    const view = render(<ClassListPage canCreateClass={false} classes={classes} />);

    const chips = screen.getByRole("group", { name: "Lọc nhanh theo trạng thái" });
    expect(within(chips).getByRole("button", { name: chip("Tất cả", 3) })).toHaveAttribute("aria-pressed", "true");
    expect(within(chips).getByRole("button", { name: chip("Đang hoạt động", 2) })).toBeEnabled();
    expect(within(chips).getByRole("button", { name: chip("Nháp", 1) })).toBeEnabled();
    expect(within(chips).getByRole("button", { name: chip("Đã đóng", 0) })).toBeDisabled();
    expect(within(chips).getByRole("button", { name: chip("Lưu trữ", 0) })).toBeDisabled();
    expect(dataRows()).toHaveLength(3);

    fireEvent.click(within(chips).getByRole("button", { name: chip("Nháp", 1) }));
    expect(historySpies.replace).toHaveBeenLastCalledWith(null, "", "/classes?status=draft");
    view.rerender(<ClassListPage canCreateClass={false} classes={classes} />);

    expect(screen.getByRole("button", { name: chip("Nháp", 1) })).toHaveAttribute("aria-pressed", "true");
    const rows = dataRows();
    expect(rows).toHaveLength(1);
    expect(rows[0]).toHaveTextContent("Toán 9C");
    expect(screen.getByText(/1 khớp bộ lọc/)).toBeInTheDocument();
  });

  it("shows the in-frame empty state for a no-match filter and restores rows through Xóa lọc", () => {
    const view = render(<ClassListPage canCreateClass={false} classes={classes} />);
    const rerender = () => view.rerender(<ClassListPage canCreateClass={false} classes={classes} />);

    fireEvent.change(screen.getByTestId("desktop-class-search"), { target: { value: "không-tồn-tại" } });
    rerender();

    expect(dataRows()).toHaveLength(0);
    expect(screen.queryByText("Chưa có lớp học")).not.toBeInTheDocument();
    const frame = screen.getByRole("table", { name: "Danh sách lớp học" }).parentElement as HTMLElement;
    expect(within(frame).getByText("Không có lớp học khớp bộ lọc")).toBeInTheDocument();
    expect(within(frame).getByText("Nới rộng điều kiện hoặc xóa bộ lọc để xem lại danh sách.")).toBeInTheDocument();

    fireEvent.click(within(frame).getByRole("button", { name: "Xóa lọc" }));
    expect(historySpies.replace).toHaveBeenLastCalledWith(null, "", "/classes");
    rerender();

    expect(dataRows()).toHaveLength(3);
    expect(screen.queryByText("Không có lớp học khớp bộ lọc")).not.toBeInTheDocument();
    expect(screen.queryByRole("button", { name: "Xóa lọc" })).not.toBeInTheDocument();
  });
});

// Value: protects=changing page pushes a history entry (Back returns to the previous page) that keeps the active filter, while filter edits still replace; fails_when=updatePage uses replaceState (Back skips pages), drops the filter, or omits page=2; why_new=existing cases only assert replaceState for filters; seam=none; no_claim=does not prove Next re-renders on pushState (the harness feeds the href back itself)
describe("Classes directory pagination history", () => {
  const manyClasses: ClassDirectoryItem[] = Array.from({ length: 21 }, (_, index) => ({
    ...classWithoutStudentCount,
    activeStudentCount: 10,
    code: `7-${index + 1}`,
    id: `class-${index + 1}`,
    name: `Toán 7-${index + 1}`,
  }));

  it("pushes a history entry for the next page and keeps the active filter", () => {
    navigation.state.params = new URLSearchParams("status=active");
    render(<ClassListPage canCreateClass={false} classes={manyClasses} />);

    const pager = screen.getByRole("navigation", { name: "Phân trang lớp học" });
    fireEvent.click(within(pager).getByRole("button", { name: "Sau" }));

    expect(historySpies.push).toHaveBeenCalledTimes(1);
    expect(historySpies.push).toHaveBeenLastCalledWith(null, "", "/classes?status=active&page=2");
    expect(historySpies.replace).not.toHaveBeenCalled();
  });

  // Value: protects=URL writes hand Next a null state so its patched History API syncs useSearchParams; fails_when=the page passes window.history.state, which carries Next's __NA marker and makes Next skip the sync (filters, chips and paging stop working in the real app); why_new=ship review pass C CRITICAL — the spies above would not notice because jsdom's state is null; seam=none; no_claim=does not run Next's patched history
  it("never forwards Next's internal history state when writing the URL", () => {
    const stateGetter = vi.spyOn(window.history, "state", "get").mockReturnValue({ __NA: true });
    try {
      navigation.state.params = new URLSearchParams("status=active");
      render(<ClassListPage canCreateClass={false} classes={manyClasses} />);

      fireEvent.click(within(screen.getByRole("navigation", { name: "Phân trang lớp học" })).getByRole("button", { name: "Sau" }));
      fireEvent.click(within(screen.getByRole("group", { name: "Lọc nhanh theo trạng thái" })).getByRole("button", { name: /^Tất cả/ }));

      for (const [data] of [...historySpies.push.mock.calls, ...historySpies.replace.mock.calls]) {
        expect(data).toBeNull();
      }
      expect(historySpies.push.mock.calls.length + historySpies.replace.mock.calls.length).toBeGreaterThanOrEqual(2);
    } finally {
      stateGetter.mockRestore();
    }
  });

  // Value: protects=after Back/Forward the next filter change builds on the URL's filters, not a stale buffer; fails_when=the pending buffer only re-syncs when equal to the rendered filters (pre-3806799), so a later change revives the abandoned filter; why_new=ship review pass C; seam=none; no_claim=does not dispatch a real popstate
  it("builds the next filter change on the URL after Back, not on a stale buffer", () => {
    navigation.state.params = new URLSearchParams("status=active");
    const view = render(<ClassListPage canCreateClass={false} classes={manyClasses} />);

    // A change the harness does not feed back yet leaves the buffer at status=active.
    fireEvent.change(screen.getByTestId("desktop-class-search"), { target: { value: "Toán" } });
    // Back: the URL now says status=closed without going through the page.
    navigation.state.params = new URLSearchParams("status=closed");
    view.rerender(<ClassListPage canCreateClass={false} classes={manyClasses} />);
    fireEvent.change(screen.getByTestId("desktop-class-search"), { target: { value: "7-1" } });

    expect(historySpies.replace).toHaveBeenLastCalledWith(null, "", expect.stringContaining("status=closed"));
    expect(historySpies.replace).toHaveBeenLastCalledWith(null, "", expect.not.stringContaining("status=active"));
  });
});
